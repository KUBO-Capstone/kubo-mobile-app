-- =====================================================================
-- Kubo PostgreSQL schema (RDS)  -  v2
--
-- Changes from v1:
--   * messages table REMOVED (messages now live in DynamoDB)
--   * conversations: last-message preview, per-user read cursors,
--     per-user hidden timestamps
--   * orders: per-user hidden timestamps + snapshot columns
--   * users: deleted_at (soft delete / anonymize), profile_photo_key
--   * product_images.image_url -> image_key (S3 object key, not URL)
--   * Foreign keys on shared records are RESTRICT, not CASCADE
--   * users: added location, business_name, business_type, profile_privacy
--     (from the teammate's SQLite changes; profile_privacy is jsonb)
--   * Hard deletes of users/orders/negotiations/products are blocked;
--     use soft delete / hiding / anonymize_user() instead
--
-- Cascade policy:
--   CASCADE   only for children that are meaningless without the parent
--             (order_items, product_images, saved_listings, ...)
--   RESTRICT  for anything the other party or accounting depends on
--   SET NULL  for optional "who did it" references (logs, notifications)
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- Addresses and users
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS addresses (
    address_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region            varchar(100) NOT NULL,
    province          varchar(100) NOT NULL,
    city_municipality varchar(100) NOT NULL,
    barangay          varchar(100) NOT NULL,
    zip_code          varchar(4)   NOT NULL,
    street_details    varchar(255),
    landmark          varchar(255),
    latitude          double precision,
    longitude         double precision
);

CREATE TABLE IF NOT EXISTS users (
    user_id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name           varchar(50)  NOT NULL,
    last_name            varchar(50)  NOT NULL,
    email                varchar(100) NOT NULL,
    password_hash        text         NOT NULL,
    contact_number       varchar(15)  NOT NULL,
    location             varchar(80),
    business_name        varchar(80),
    business_type        varchar(40),
    -- Stored as jsonb (was a JSON string in SQLite). node-postgres returns it
    -- already parsed, so do NOT JSON.parse() it in the app.
    profile_privacy      jsonb        NOT NULL DEFAULT
                         '{"public_profile":true,"show_bio":true,"show_contact_number":true,"show_location":true}'::jsonb,
    role                 varchar(20)  NOT NULL DEFAULT 'consumer'
                         CHECK (role IN ('farmer', 'consumer', 'admin')),
    preferred_address_id integer,
    is_verified          boolean      NOT NULL DEFAULT FALSE,
    profile_photo_key    text,                       -- S3 object key, not a URL
    bio                  text         NOT NULL DEFAULT '',
    created_at           timestamptz  NOT NULL DEFAULT now(),
    deleted_at           timestamptz,                -- set by anonymize_user()

    FOREIGN KEY (preferred_address_id) REFERENCES addresses (address_id) ON DELETE SET NULL
);

-- Case-insensitive unique email. Always lowercase emails in the app too.
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_lower ON users (lower(email));

CREATE TABLE IF NOT EXISTS user_addresses (
    user_id    integer NOT NULL,
    address_id integer NOT NULL,
    PRIMARY KEY (user_id, address_id),
    FOREIGN KEY (user_id)    REFERENCES users (user_id)        ON DELETE CASCADE,
    FOREIGN KEY (address_id) REFERENCES addresses (address_id) ON DELETE CASCADE
);

-- Farm location and vetting state for users whose role is 'farmer'.
-- Distinct from users.preferred_address_id, which is the consumer-side
-- pickup area and must not be used as a farm location.
CREATE TABLE IF NOT EXISTS farmer_profiles (
    farmer_id           integer PRIMARY KEY,
    address_id          integer     NOT NULL UNIQUE,
    verification_status varchar(20) NOT NULL DEFAULT 'pending'
                        CHECK (verification_status IN ('pending', 'verified', 'rejected')),

    FOREIGN KEY (farmer_id)  REFERENCES users (user_id)        ON DELETE CASCADE,
    FOREIGN KEY (address_id) REFERENCES addresses (address_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS bagsakan_centers (
    center_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address_id    integer      NOT NULL,
    location_name varchar(100) NOT NULL,

    FOREIGN KEY (address_id) REFERENCES addresses (address_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- Products (never hard-deleted: use status = 'delisted')
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS products (
    product_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id          integer       NOT NULL,
    crop_name          varchar(100)  NOT NULL,
    category           varchar(20)   NOT NULL
                       CHECK (category IN ('vegetable', 'fruit', 'grain', 'legume', 'herb', 'spice')),
    base_price         numeric(12,2) NOT NULL CHECK (base_price >= 0),
    available_quantity numeric(12,3) NOT NULL CHECK (available_quantity >= 0),
    unit_measurement   varchar(20)   NOT NULL
                       CHECK (unit_measurement IN ('kg', 'g', 'lb', 'oz', 'liter', 'ml', 'piece')),
    status             varchar(20)   NOT NULL DEFAULT 'available'
                       CHECK (status IN ('available', 'out of stock', 'delisted')),
    created_at         timestamptz   NOT NULL DEFAULT now(),
    updated_at         timestamptz   NOT NULL DEFAULT now(),

    FOREIGN KEY (seller_id) REFERENCES users (user_id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS product_images (
    image_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    integer NOT NULL,
    image_key     text    NOT NULL,                  -- S3 object key, e.g. products/42/<uuid>.jpg
    display_order integer NOT NULL,

    FOREIGN KEY (product_id) REFERENCES products (product_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- Conversations (metadata only; the messages themselves are in DynamoDB)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS conversations (
    conversation_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id                integer     NOT NULL,
    seller_id               integer     NOT NULL,
    product_id              integer,

    -- Inbox list data, updated by the app after each DynamoDB write
    last_message_at         timestamptz,
    last_message_sender_id  integer,
    last_message_preview    varchar(200),

    -- Read cursors. A conversation is unread for the buyer when
    --   last_message_at > buyer_last_read_at AND last_message_sender_id <> buyer_id
    buyer_last_read_at      timestamptz,
    seller_last_read_at     timestamptz,

    -- Per-user "delete chat". The other participant still sees it.
    -- The app should clear the hidden column when a new message arrives.
    buyer_hidden_at         timestamptz,
    seller_hidden_at        timestamptz,

    created_at              timestamptz NOT NULL DEFAULT now(),

    CHECK (buyer_id <> seller_id),
    FOREIGN KEY (buyer_id)               REFERENCES users (user_id)       ON DELETE RESTRICT,
    FOREIGN KEY (seller_id)              REFERENCES users (user_id)       ON DELETE RESTRICT,
    FOREIGN KEY (last_message_sender_id) REFERENCES users (user_id)       ON DELETE SET NULL,
    FOREIGN KEY (product_id)             REFERENCES products (product_id) ON DELETE SET NULL
);

-- ---------------------------------------------------------------------
-- Negotiations and orders (shared records: never hard-deleted)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS negotiations (
    negotiation_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id  integer       NOT NULL,
    product_id       integer       NOT NULL,
    buyer_id         integer       NOT NULL,
    seller_id        integer       NOT NULL,
    offered_price    numeric(12,2) NOT NULL CHECK (offered_price > 0),
    offered_quantity numeric(12,3) NOT NULL CHECK (offered_quantity > 0),
    status           varchar(20)   NOT NULL DEFAULT 'pending'
                     CHECK (status IN ('pending', 'countered', 'accepted', 'declined')),
    created_at       timestamptz   NOT NULL DEFAULT now(),

    CHECK (buyer_id <> seller_id),
    FOREIGN KEY (conversation_id) REFERENCES conversations (conversation_id) ON DELETE RESTRICT,
    FOREIGN KEY (product_id)      REFERENCES products (product_id)           ON DELETE RESTRICT,
    FOREIGN KEY (buyer_id)        REFERENCES users (user_id)                 ON DELETE RESTRICT,
    FOREIGN KEY (seller_id)       REFERENCES users (user_id)                 ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS orders (
    order_id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negotiation_id          integer       NOT NULL UNIQUE,
    buyer_id                integer       NOT NULL,
    seller_id               integer       NOT NULL,
    drop_off_center_id      integer,
    drop_off_location_name  varchar(100),            -- snapshot taken at order time
    total_amount            numeric(12,2) NOT NULL CHECK (total_amount >= 0),
    order_status            varchar(20)   NOT NULL DEFAULT 'pending'
                            CHECK (order_status IN ('pending', 'in transit', 'delivered', 'cancelled')),
    delivery_method         varchar(20)   NOT NULL
                            CHECK (delivery_method IN ('courier', 'meetup')),

    -- Per-user "delete order". Each party hides it from their own list only.
    buyer_hidden_at         timestamptz,
    seller_hidden_at        timestamptz,

    order_date              timestamptz   NOT NULL DEFAULT now(),
    updated_at              timestamptz   NOT NULL DEFAULT now(),

    CHECK (buyer_id <> seller_id),
    FOREIGN KEY (negotiation_id)     REFERENCES negotiations (negotiation_id) ON DELETE RESTRICT,
    FOREIGN KEY (buyer_id)           REFERENCES users (user_id)               ON DELETE RESTRICT,
    FOREIGN KEY (seller_id)          REFERENCES users (user_id)               ON DELETE RESTRICT,
    FOREIGN KEY (drop_off_center_id) REFERENCES bagsakan_centers (center_id)  ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS order_items (
    order_item_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         integer       NOT NULL,
    product_id       integer       NOT NULL,
    -- Snapshots: the order must read the same even if the product is edited later
    product_name     varchar(100)  NOT NULL,
    unit_measurement varchar(20)   NOT NULL,
    quantity         numeric(12,3) NOT NULL CHECK (quantity > 0),
    negotiated_price numeric(12,2) NOT NULL CHECK (negotiated_price >= 0),

    FOREIGN KEY (order_id)   REFERENCES orders (order_id)     ON DELETE CASCADE,
    FOREIGN KEY (product_id) REFERENCES products (product_id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS reviews (
    review_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    integer NOT NULL,
    reviewer_id integer NOT NULL,
    reviewee_id integer NOT NULL,
    rating      integer CHECK (rating >= 1 AND rating <= 5),
    comment     text,
    created_at  timestamptz NOT NULL DEFAULT now(),

    CHECK (reviewer_id <> reviewee_id),
    UNIQUE (order_id, reviewer_id),                  -- one review per party per order
    FOREIGN KEY (order_id)    REFERENCES orders (order_id) ON DELETE RESTRICT,
    FOREIGN KEY (reviewer_id) REFERENCES users (user_id)   ON DELETE RESTRICT,
    FOREIGN KEY (reviewee_id) REFERENCES users (user_id)   ON DELETE RESTRICT
);

