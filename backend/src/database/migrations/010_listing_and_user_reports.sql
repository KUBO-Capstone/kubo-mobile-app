-- Reports of a listing or an account, sent from the listing page and from a
-- profile ("Report this listing" / "Report this profile").
--   * Kept apart from `reports`, which is app feedback and bug reports.
--   * product_id is set for a listing report and NULL for a profile report.
--     reported_user_id is always set: for a listing it is the seller at the
--     time of the report, so every report about one account can be found in
--     one place.
--   * status is for whoever reviews them: 'open' until then.
--   * One open report per reporter and listing, and per reporter and
--     profile, so tapping Submit twice does not file two.
--   * Rows point at users and products, which are never really deleted
--     (anonymize_user() and 'delisted' are the soft deletes), so the
--     foreign keys refuse a DELETE rather than lose the report.
BEGIN;

CREATE TABLE IF NOT EXISTS moderation_reports (
    report_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id      integer     NOT NULL,
    reported_user_id integer     NOT NULL,
    product_id       integer,
    reason           text        NOT NULL CHECK (char_length(reason) BETWEEN 1 AND 1000),
    status           text        NOT NULL DEFAULT 'open'
                     CHECK (status IN ('open', 'resolved', 'dismissed')),
    created_at       timestamptz NOT NULL DEFAULT now(),

    CHECK (reporter_id <> reported_user_id),
    FOREIGN KEY (reporter_id)      REFERENCES users (user_id)       ON DELETE RESTRICT,
    FOREIGN KEY (reported_user_id) REFERENCES users (user_id)       ON DELETE RESTRICT,
    FOREIGN KEY (product_id)       REFERENCES products (product_id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_moderation_reports_reported_user ON moderation_reports (reported_user_id);
CREATE INDEX IF NOT EXISTS idx_moderation_reports_product       ON moderation_reports (product_id) WHERE product_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_moderation_reports_open          ON moderation_reports (created_at) WHERE status = 'open';

CREATE UNIQUE INDEX IF NOT EXISTS uq_moderation_reports_open_listing
    ON moderation_reports (reporter_id, product_id)
    WHERE status = 'open' AND product_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_moderation_reports_open_profile
    ON moderation_reports (reporter_id, reported_user_id)
    WHERE status = 'open' AND product_id IS NULL;

COMMIT;
